#!/usr/bin/env python3
"""
Patch the generated Capacitor Android project for the Color World Kids APK:

  1. copy the custom GallerySaver plugin into the app sources
  2. register it in MainActivity (registerPlugin(GallerySaver.class))
  3. make sure the FileProvider is declared (needed by the Android share sheet)
     together with its file_paths.xml

Idempotent — safe to run on every build. Handles the Capacitor project
generated by `npx cap add android` (any recent Capacitor version).

Usage: python3 apk-kit/native/patch_android.py [android-project-dir]
"""
import os
import sys

KIT = os.path.dirname(os.path.abspath(__file__))
ANDROID = sys.argv[1] if len(sys.argv) > 1 else os.path.join(KIT, "..", "android")

APP_MAIN = os.path.join(ANDROID, "app", "src", "main")
PKG_DIR = os.path.join(APP_MAIN, "java", "com", "candyteam", "colorworld")

# ---------------------------------------------------------------- 1. plugin
if not os.path.isdir(PKG_DIR):
    sys.exit(f"ERROR: app package folder missing: {PKG_DIR} — run cap add android first")
with open(os.path.join(KIT, "GallerySaver.java"), encoding="utf-8") as f:
    plugin_src = f.read()
with open(os.path.join(PKG_DIR, "GallerySaver.java"), "w", encoding="utf-8") as f:
    f.write(plugin_src)
print("  GallerySaver.java copied into the app sources")

# ------------------------------------------------------- 2. MainActivity
MAINACT = os.path.join(PKG_DIR, "MainActivity.java")
FULL_MAINACT = """package com.candyteam.colorworld;

import android.os.Bundle;

import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
    @Override
    public void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        registerPlugin(GallerySaver.class);
    }
}
"""
with open(MAINACT, encoding="utf-8") as f:
    s = f.read()
if "registerPlugin(GallerySaver.class)" not in s:
    if "super.onCreate(savedInstanceState);" in s:
        # classic template — insert the registration line
        s = s.replace(
            "super.onCreate(savedInstanceState);",
            "super.onCreate(savedInstanceState);\n        registerPlugin(GallerySaver.class);",
            1,
        )
    else:
        # Capacitor 8+ one-line template — rewrite the whole file
        s = FULL_MAINACT
    with open(MAINACT, "w", encoding="utf-8") as f:
        f.write(s)
    print("  MainActivity patched: GallerySaver registered")
else:
    print("  MainActivity already registers GallerySaver")

# --------------------------------------------- 3. FileProvider for sharing
MANIFEST = os.path.join(APP_MAIN, "AndroidManifest.xml")
with open(MANIFEST, encoding="utf-8") as f:
    manifest = f.read()

PROVIDER = (
    "        <provider\n"
    '            android:name="androidx.core.content.FileProvider"\n'
    '            android:authorities="${applicationId}.fileprovider"\n'
    '            android:exported="false"\n'
    '            android:grantUriPermissions="true">\n'
    "            <meta-data\n"
    '                android:name="android.support.FILE_PROVIDER_PATHS"\n'
    '                android:resource="@xml/file_paths" />\n'
    "        </provider>\n"
)
if "FileProvider" in manifest:
    print("  AndroidManifest already declares a FileProvider")
else:
    if "</application>" not in manifest:
        sys.exit("ERROR: unexpected AndroidManifest template")
    manifest = manifest.replace("</application>", PROVIDER + "    </application>", 1)
    with open(MANIFEST, "w", encoding="utf-8") as f:
        f.write(manifest)
    print("  AndroidManifest patched: FileProvider added")

XML_DIR = os.path.join(APP_MAIN, "res", "xml")
os.makedirs(XML_DIR, exist_ok=True)
PATHS = os.path.join(XML_DIR, "file_paths.xml")
if not os.path.exists(PATHS):
    with open(PATHS, "w", encoding="utf-8") as f:
        f.write(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            "<paths>\n"
            '    <cache-path name="cache" path="." />\n'
            '    <files-path name="files" path="." />\n'
            '    <external-cache-path name="ext-cache" path="." />\n'
            '    <external-files-path name="ext-files" path="." />\n'
            "</paths>\n"
        )
    print("  file_paths.xml created")
else:
    print("  file_paths.xml already present")

print("  Android project patch complete")
