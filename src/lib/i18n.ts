export const dict: Record<Lang, Record<TKey, string>> = { fa, en }

export type T = (k: TKey) => string

export const makeT = (lang: Lang): T => (k) => dict[lang][k]

/** Persian digits for numbers when in Farsi mode. */
export const num = (n: number | string, lang: Lang): string => {
  const s = String(n)
  if (lang !== 'fa') return s
  return s.replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)])
}

/** Translate with {n} interpolation. */
export const tf = (t: T, k: TKey, n: number, lang: Lang): string =>
  (t(k) as string).replace('{n}', num(n, lang))
